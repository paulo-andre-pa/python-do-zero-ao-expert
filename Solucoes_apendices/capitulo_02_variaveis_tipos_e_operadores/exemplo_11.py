# Capítulo 2 — Variáveis, tipos e operadores
# Secção: Números inteiros e decimais

import math

print(abs(-7))             # valor absoluto
print(round(3.14159, 2))   # arredondar a 2 casas
print(max(4, 9, 2), min(4, 9, 2))
print(pow(2, 10))
print(math.sqrt(144), math.floor(3.7), math.ceil(3.2))
print(divmod(17, 5))       # (quociente, resto)
