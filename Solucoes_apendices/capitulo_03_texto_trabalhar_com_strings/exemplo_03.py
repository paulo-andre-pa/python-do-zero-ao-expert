# Capítulo 3 — Texto: trabalhar com strings
# Secção: Strings são sequências

s = "Programação"
print(s[0:3])     # do índice 0 ao 2
print(s[3:])      # do 3 até ao fim
print(s[:5])      # os 5 primeiros
print(s[-3:])     # os 3 últimos
print(s[::2])     # um sim, um não
print(s[::-1])    # invertida
